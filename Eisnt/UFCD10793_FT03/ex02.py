"""Implementa um programa que leia dois números e indique se estes são iguais ou 
diferentes. """

print("Digite dois números inteiros:")

numero1 = int(input("Digite o número1: \n"))
numero2 = int(input("Digite o número2: \n"))
if numero1 == numero2:
    print("Estes números são iguais")
else:
    print("Números diferentes")
