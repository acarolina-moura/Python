"""1. Escreve um programa que solicite duas notas ([nota1] e [nota2]) ao utilizador e
apresente a média das mesmas da seguinte forma: “A média das notas [nota1] e
[nota2] é [média]."""

nota1 = int(input("Digite a primeira nota: \n"))
nota2 = int(input("Digite a segunda nota: \n"))

media = (nota1 + nota2) / 2

print(f"A média das notas {nota1} e {nota2} é {media}")
    
    