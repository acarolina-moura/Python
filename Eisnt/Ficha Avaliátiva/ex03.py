"""3. Escreve um programa que solicite um número inteiro ao utilizador e caso o mesmo seja
maior que 20, devolva o resultado da sua divisão por 2."""

numero = int(input("Digite um número inteiro: \n"))

if numero > 20:
    print(f"O número é maior do que 20. O resultado da divisão de {numero} por 2 é ", numero / 2)
else:
        print("O número não é maior que 20")
    
    