"""Escreve um programa em python que solicite três números inteiros ao utilizador e
imprima a soma dos mesmos."""

print("Digite três números:")

numero1 = int(input("Digite o número1: \n"))
numero2 = int(input("Digite o número2: \n"))
numero3 = int(input("Digite o número3: \n"))

print(f" A soma dos números é: {numero1+numero2+numero3}")
